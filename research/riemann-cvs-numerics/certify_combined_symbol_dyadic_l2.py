    target = _fraction_arb(target_scaled_upper)

    all_prime_data = prime_powers_up_to(c)
    prime_data = [(q, p) for q, p in all_prime_data if q < c]
    endpoint_events = [(q, p) for q, p in all_prime_data if q == c]
    if not prime_data:
        raise ValueError("no nontrivial prime-power phases were found")

    weights = [arb(p).log() / arb(q).sqrt() for q, p in prime_data]
    phases = [2 * pi * arb(q).log() / length for q, _ in prime_data]

    labelled_denominators: list[tuple[str, arb]] = []
    half_sines: list[arb] = []
    double_half_sines: list[arb] = []
    for (q, _p), phase in zip(prime_data, phases):
        half = abs((phase / 2).sin())
        doubled = abs(phase.sin())
        half_sines.append(half)
        double_half_sines.append(doubled)
        labelled_denominators.append((f"single:{q}", half))
        labelled_denominators.append((f"diagonal:{q}", doubled))

    pair_denominators: list[tuple[arb, arb]] = []
    for i in range(len(phases)):
        for j in range(i + 1, len(phases)):
            difference = abs(((phases[i] - phases[j]) / 2).sin())
            total = abs(((phases[i] + phases[j]) / 2).sin())
            pair_denominators.append((difference, total))
            q_i = prime_data[i][0]
            q_j = prime_data[j][0]
            labelled_denominators.append((f"pair-difference:{q_i}:{q_j}", difference))
            labelled_denominators.append((f"pair-sum:{q_i}:{q_j}", total))

    if not all(value > 0 for _, value in labelled_denominators):
        raise RuntimeError("a geometric-sum phase denominator is not positive")
    minimum_label, minimum_denominator = _minimum_labelled(labelled_denominators)

    main = center**2 + sum((weight**2 for weight in weights), arb(0)) / 2
    symbol_abs = center + sum(weights, arb(0))

    linear_error = (
        2
        * center
        * sum(
            (weight / denominator for weight, denominator in zip(weights, half_sines)),
            arb(0),
        )
    )
    diagonal_error = sum(
        (
            weight**2 / (2 * denominator)
            for weight, denominator in zip(weights, double_half_sines)
        ),
        arb(0),
    )
    pair_error = arb(0)
    pair_index = 0
    for i in range(len(weights)):
        for j in range(i + 1, len(weights)):
            difference, total = pair_denominators[pair_index]
            pair_error += weights[i] * weights[j] * (1 / difference + 1 / total)
            pair_index += 1
    geometric_error = linear_error + diagonal_error + pair_error

    linear_decay_coefficient = 2 * decay * symbol_abs
    quadratic_decay_coefficient = decay**2

    n = arb(start_mode)
    prefix_slope = (
        main + linear_decay_coefficient / n + quadratic_decay_coefficient / n**2
    )
    scaled_weighted_upper = prefix_slope / 2 + geometric_error * n / (n + 1) ** 2
    if not scaled_weighted_upper < target:
        raise RuntimeError(
            "combined-symbol dyadic L2 target failed: "
            f"upper={scaled_weighted_upper}, target={target}"
        )

    monotone_coefficients = [
        linear_decay_coefficient,
        quadratic_decay_coefficient,
        geometric_error,
    ]
    if not all(value >= 0 for value in monotone_coefficients):
        raise RuntimeError("a decaying endpoint coefficient is negative")

    script_dir = Path(__file__).resolve().parent
    prime_power_source = script_dir / "certify_parity_gap.py"

