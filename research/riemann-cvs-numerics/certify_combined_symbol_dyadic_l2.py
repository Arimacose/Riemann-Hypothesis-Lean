"""Certify a uniform dyadic L2 bound for the combined odd Loewner symbol.

For the V23 cutoff c=13, write F_n = S_n + P_n.  The workflow-produced
Archimedean certificate, generated by its tracked certifier, proves
abs(S_n-pi/4) <= D/n with D=1/4, while P_n is the finite prime-power sine
polynomial.  The endpoint q=c has phase 2*pi*n and vanishes exactly.

Expanding (pi/4+P_n)^2 leaves a constant mean plus finitely many geometric
sums.  Every prefix N<n<=N+r therefore has an affine square-sum upper bound.
Finite Abel summation and the reciprocal-square dyadic estimate then give

    N * sum_(N<n<=2N) F_n^2/n^2
      <= A(N)/2 + B*N/(N+1)^2.

All decaying coefficients are nonnegative, and N/(N+1)^2 decreases for
integer N>=1, so a strict check at one start mode controls every later mode.
Arb is used for every transcendental value and strict comparison.

The output is a rigorous constant-composition certificate.  Its proof-level
use remains conditional on the analytic Archimedean source identification and
the parity-shell operator bridge.  The companion Lean module now identifies
the literal finite prime entrywise builder with the normalized logarithmic
Loewner kernel, formalizes the finite geometric-sum inequality itself, the
exact logarithmic prime weights and phases, and symbolic nonresonance of every
single, doubled, pair-difference, and pair-sum phase in the tracked cutoff-13
event list, as well as the Abel, dyadic, endpoint-monotonicity, and
rectangular-Cauchy adapters.  This script independently interval-certifies the
positive denominator magnitudes needed for the numerical constants below.
"""

