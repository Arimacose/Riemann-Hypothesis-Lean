def _positive_fraction(text: str, name: str) -> Fraction:
    value = Fraction(text)
    if value <= 0:
        raise ValueError(f"{name} must be strictly positive")
    return value


def _fraction_arb(value: Fraction) -> arb:
    return arb(value.numerator) / arb(value.denominator)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def _git_sha() -> str | None:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            text=True,
            encoding="utf-8",
            stderr=subprocess.DEVNULL,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def _ball_record(value: arb, digits: int = 70) -> dict[str, str]:
    return {
        "midpoint": value.mid().str(digits, radius=False),
        "radius": value.rad().str(20, radius=False),
        "lower": value.lower().str(digits, radius=True),
        "upper": value.upper().str(digits, radius=True),
    }


def _load_json(path: Path, name: str) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"could not read {name}: {path}: {exc}") from exc
    if not isinstance(payload, dict):
        raise ValueError(f"{name} must contain a JSON object")
    return payload


def _require_true(payload: dict[str, Any], key: str, name: str) -> None:
    if payload.get(key) is not True:
        raise ValueError(f"{name} does not certify {key}=true")


def _validate_archimedean_certificate(
    *,
    path: Path,
    c: int,
    start_mode: int,
    centered_decay: Fraction,
    precision: int,
) -> tuple[dict[str, Any], dict[str, Any]]:
    payload = _load_json(path, "Archimedean certificate")
    if payload.get("status") != "PASS":
        raise ValueError("Archimedean certificate must have status PASS")
    _require_true(
        payload,
        "rigorous_constant_certificate",
        "Archimedean certificate",
    )
    if payload.get("c") != c:
        raise ValueError("Archimedean certificate cutoff does not match --c")

    minimum_mode = payload.get("minimum_mode")
    if not isinstance(minimum_mode, int) or minimum_mode > start_mode:
        raise ValueError(
            "Archimedean certificate does not cover the requested start mode"
        )
    certificate_precision = payload.get("precision_bits")
    if not isinstance(certificate_precision, int) or certificate_precision < precision:
        raise ValueError(
            "Archimedean certificate precision is below the requested precision"
        )

    centered = payload.get("centered_symbol_audit")
    if not isinstance(centered, dict):
        raise ValueError("Archimedean certificate lacks centered_symbol_audit")
    if centered.get("target_decay_coefficient") != str(centered_decay):
        raise ValueError("Archimedean centered-decay coefficient mismatch")
    _require_true(centered, "strict_upper_pass", "Archimedean centered audit")
    _require_true(centered, "strict_lower_pass", "Archimedean centered audit")

    script = Path(__file__).resolve().parent / ("certify_archimedean_tail_envelope.py")
    expected_script_hash = str(payload.get("script_sha256", "")).upper()
    actual_script_hash = _sha256(script)
    if expected_script_hash != actual_script_hash:
        raise ValueError(
            "Archimedean certificate script hash mismatch: "
            f"artifact={expected_script_hash}, current={actual_script_hash}"
        )

    current_git = _git_sha()
    certificate_git = payload.get("git_sha")
    if not isinstance(current_git, str) or len(current_git) != 40:
        raise ValueError("current checkout has no valid 40-character Git SHA")
    if not isinstance(certificate_git, str) or len(certificate_git) != 40:
        raise ValueError("Archimedean certificate has no valid 40-character Git SHA")
    if certificate_git != current_git:
        raise ValueError(
            "Archimedean certificate commit does not match the current checkout"
        )

    metadata = {
        "path": str(path.resolve()),
        "sha256": _sha256(path.resolve()),
        "script_path": str(script),
        "script_sha256": actual_script_hash,
        "git_sha": certificate_git,
        "minimum_mode": minimum_mode,
        "precision_bits": certificate_precision,
        "centered_decay_coefficient": str(centered_decay),
    }
    return payload, metadata


def _minimum_labelled(
    values: list[tuple[str, arb]],
) -> tuple[str, arb]:
    if not values:
        raise ValueError("phase denominator list is empty")
    label, value = values[0]
    for candidate_label, candidate in values[1:]:
        if candidate < value:
            label, value = candidate_label, candidate
    return label, value


